// Generate SQL that creates the two test accounts.
//
//   node scripts/seed-users.mjs
//   npx wrangler d1 execute buy-this-for-me --remote --file seeds/test-users.sql
//
// Writes seeds/test-users.sql (git-ignored). The password is hashed here, so
// the file never contains a plain password. Re-running it is safe: the insert
// updates the hash and role of an existing account.

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { hashPassword } from '../src/auth.js';

// Test accounts. Change both passwords before anyone else uses this.
const TEST_ACCOUNTS = [
  { username: 'alex', password: '1234', role: 'user' },
  { username: 'martin', password: '1234', role: 'admin' },
];

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const lines = [
  '-- Generated by scripts/seed-users.mjs. Do not commit this file.',
  '-- Test accounts only: change these passwords before real use.',
  '',
];

for (const account of TEST_ACCOUNTS) {
  const hash = await hashPassword(account.password);
  const createdAt = new Date().toISOString();
  lines.push(
    'INSERT INTO users (username, password_hash, role, created_at) VALUES ' +
      `(${sqlString(account.username)}, ${sqlString(hash)}, ${sqlString(account.role)}, ${sqlString(createdAt)}) ` +
      'ON CONFLICT(username) DO UPDATE SET password_hash = excluded.password_hash, role = excluded.role;'
  );
}

lines.push('');

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'seeds', 'test-users.sql');
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, lines.join('\n'), 'utf8');

console.log(`Wrote ${outputPath}`);
console.log('Accounts: alex (user), martin (admin). Password for both: 1234');
console.log('Apply it with:');
console.log('  npx wrangler d1 execute buy-this-for-me --remote --file seeds/test-users.sql');
